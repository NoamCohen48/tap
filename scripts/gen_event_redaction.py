#!/usr/bin/env python3
"""Generate reflection-free, known-field-only event redaction from the protobuf schema.

Requires the grpcio-tools pinned by clients/python/scripts/gen_stubs.py. Unknown wire fields
are deliberately not copied. Run with --check in verification after any schema change.
"""
from __future__ import annotations

import pathlib
import subprocess
import sys
import tempfile

from google.protobuf import descriptor_pb2 as dp

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "host/daemon/src/main/kotlin/io/github/noamcohen48/tap/daemon/core/EventRedaction.kt"
JAVA = "io.github.noamcohen48.tap.api.v1."
JSON_OUTPUT = ROOT / "clients/kotlin/sdk/src/main/kotlin/io/github/noamcohen48/tap/sdk/EventJson.kt"


def generate() -> dict[pathlib.Path, str]:
    with tempfile.TemporaryDirectory() as temp:
        descriptor = pathlib.Path(temp) / "schema.pb"
        subprocess.run([sys.executable, "-m", "grpc_tools.protoc", f"-I{ROOT / 'contracts/proto'}",
            "--include_imports", f"--descriptor_set_out={descriptor}", "event_log.proto"], check=True)
        schema = dp.FileDescriptorSet.FromString(descriptor.read_bytes())
    messages = {}

    def collect(prefix, declarations):
        for message in declarations:
            name = f"{prefix}.{message.name}"
            messages[name] = message
            collect(name, message.nested_type)

    for file in schema.file:
        collect(file.package, file.message_type)
    reached = set()

    def visit(name):
        if name in reached:
            return
        reached.add(name)
        for field in messages[name].field:
            if field.type == dp.FieldDescriptorProto.TYPE_MESSAGE:
                visit(field.type_name.lstrip("."))

    visit("tap.v1.LoggedEvent")
    lines = ["// Generated by scripts/gen_event_redaction.py; do not edit.",
        "// Copy known fields only; unknown payloads and free-form failure text are not retained.",
        "package io.github.noamcohen48.tap.daemon.core", "",
        "private fun redactedString(value: String, redact: (String) -> String): String =",
        "    if (value.isEmpty()) value else redact(value)", ""]
    for name in sorted(reached):
        short = name.removeprefix("tap.v1.")
        type_name = JAVA + short
        function = "redact" + short.replace(".", "")
        lines += [f"internal fun {function}(value: {type_name}, redact: (String) -> String): {type_name} =",
            f"    {type_name}.newBuilder().apply {{"]
        for field in messages[name].field:
            # Free-form diagnostic output is not necessary to preserve the outcome code.
            if (short in {"Error", "Failure"} and field.name in {"message", "last_state"}) or field.type == dp.FieldDescriptorProto.TYPE_BYTES:
                continue
            suffix = "".join(word[:1].upper() + word[1:] for word in field.name.split("_"))
            repeated = field.label == dp.FieldDescriptorProto.LABEL_REPEATED
            enum = field.type == dp.FieldDescriptorProto.TYPE_ENUM
            getter = f"value.get{suffix}{'Value' if enum else ''}{'List' if repeated else ''}()"
            if field.type == dp.FieldDescriptorProto.TYPE_MESSAGE:
                nested = "redact" + field.type_name.removeprefix(".tap.v1.").replace(".", "")
                expression = f"{getter}.map {{ {nested}(it, redact) }}" if repeated else f"{nested}({getter}, redact)"
            elif field.type == dp.FieldDescriptorProto.TYPE_STRING:
                transform = '{ "<redacted>" }' if "Clipboard" in short else "redact"
                expression = f"{getter}.map {{ redactedString(it, {transform}) }}" if repeated else f"redactedString({getter}, {transform})"
            else:
                expression = getter
            setter = f"{'addAll' if repeated else 'set'}{suffix}{'Value' if enum else ''}({expression})"
            presence = not repeated and (field.type == dp.FieldDescriptorProto.TYPE_MESSAGE or field.proto3_optional or field.HasField("oneof_index"))
            lines.append(f"        if (value.has{suffix}()) {setter}" if presence else f"        {setter}")
        lines += ["    }.build()", ""]
    return {OUTPUT: "\n".join(lines), JSON_OUTPUT: generate_json(messages, reached)}


def generate_json(messages, reached) -> str:
    lines = ["// Generated by scripts/gen_event_redaction.py; do not edit.",
        "// Known-field proto3 JSON, without runtime protobuf reflection.",
        "package io.github.noamcohen48.tap.sdk", "",
        "import kotlinx.serialization.json.JsonArray", "import kotlinx.serialization.json.JsonObject",
        "import kotlinx.serialization.json.JsonPrimitive", "import kotlinx.serialization.json.buildJsonObject", ""]
    for name in sorted(reached):
        short = name.removeprefix("tap.v1.")
        lines += [f"internal fun eventJson(value: {JAVA + short}): JsonObject = buildJsonObject {{"]
        for field in messages[name].field:
            suffix = "".join(word[:1].upper() + word[1:] for word in field.name.split("_"))
            repeated = field.label == dp.FieldDescriptorProto.LABEL_REPEATED
            getter = f"value.get{suffix}{'List' if repeated else ''}()"
            value = "item" if repeated else getter
            if field.type == dp.FieldDescriptorProto.TYPE_MESSAGE:
                expression = f"eventJson({value})"
            elif field.type == dp.FieldDescriptorProto.TYPE_ENUM:
                raw = f"value.get{suffix}ValueList()[index]" if repeated else f"value.get{suffix}Value()"
                expression = f'if ({value}.name == "UNRECOGNIZED") JsonPrimitive({raw}) else JsonPrimitive({value}.name)'
            elif field.type in {dp.FieldDescriptorProto.TYPE_INT64, dp.FieldDescriptorProto.TYPE_SINT64, dp.FieldDescriptorProto.TYPE_SFIXED64}:
                expression = f"JsonPrimitive({value}.toString())"
            elif field.type in {dp.FieldDescriptorProto.TYPE_UINT64, dp.FieldDescriptorProto.TYPE_FIXED64}:
                expression = f"JsonPrimitive({value}.toULong().toString())"
            elif field.type in {dp.FieldDescriptorProto.TYPE_UINT32, dp.FieldDescriptorProto.TYPE_FIXED32}:
                expression = f"JsonPrimitive({value}.toUInt().toLong())"
            elif field.type == dp.FieldDescriptorProto.TYPE_BYTES:
                expression = f"JsonPrimitive(java.util.Base64.getEncoder().encodeToString({value}.toByteArray()))"
            elif field.type in {dp.FieldDescriptorProto.TYPE_FLOAT, dp.FieldDescriptorProto.TYPE_DOUBLE}:
                expression = f"if ({value}.isFinite()) JsonPrimitive({value}) else JsonPrimitive({value}.toString())"
            else:
                expression = f"JsonPrimitive({value})"
            if repeated:
                expression = f"JsonArray({getter}.mapIndexed {{ index, item -> {expression} }})"
                condition = f"{getter}.isNotEmpty()"
            elif field.type == dp.FieldDescriptorProto.TYPE_MESSAGE or field.proto3_optional or field.HasField("oneof_index"):
                condition = f"value.has{suffix}()"
            elif field.type in {dp.FieldDescriptorProto.TYPE_STRING, dp.FieldDescriptorProto.TYPE_BYTES}:
                condition = f"!{getter}.isEmpty()"
            elif field.type == dp.FieldDescriptorProto.TYPE_BOOL:
                condition = getter
            elif field.type == dp.FieldDescriptorProto.TYPE_ENUM:
                condition = f"value.get{suffix}Value() != 0"
            else:
                condition = f"{getter} != 0{'f' if field.type == dp.FieldDescriptorProto.TYPE_FLOAT else '.0' if field.type == dp.FieldDescriptorProto.TYPE_DOUBLE else 'L' if field.type in {3, 4, 6, 16, 18} else ''}"
            lines.append(f'    if ({condition}) put("{field.name}", {expression})')
        lines += ["}", ""]
    return "\n".join(lines)


def main() -> int:
    for output, content in generate().items():
        if "--check" in sys.argv:
            if not output.exists() or output.read_text() != content:
                print(f"stale generated event support: run {pathlib.Path(__file__).relative_to(ROOT)}", file=sys.stderr)
                return 1
        else:
            output.write_text(content)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
