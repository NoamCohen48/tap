"""Generate the Android key table for both SDKs: Python ``tap_e2e.Key`` and Kotlin ``Keys``.

    python clients/python/scripts/gen_keys.py ~/Android/Sdk/platforms/android-36/android.jar

Reads every ``KeyEvent.KEYCODE_*`` constant with the JDK's javap (on PATH, or JAVA_HOME/bin).
Key codes never change between Android versions; new ones are only added, so the table is
regenerated rarely, from the newest platform. A member is the constant's name without the
``KEYCODE_`` prefix (``VOLUME_UP``), except names that would start with a digit, which keep it
(``KEYCODE_0`` is the digit 0, ``KEYCODE_11`` the key labelled 11). tap-agent reads its key names
from the Python table.
"""
from __future__ import annotations

import os
import pathlib
import re
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
PYTHON = ROOT / "clients" / "python" / "tap_e2e" / "keys.py"
KOTLIN = ROOT / "clients" / "kotlin" / "sdk" / "src" / "main" / "kotlin" / "io" / "github" / "noamcohen48" / "tap" / "sdk" / "Keys.kt"


def javap() -> str:
    home = os.environ.get("JAVA_HOME")
    found = str(pathlib.Path(home) / "bin" / "javap") if home else shutil.which("javap")
    if not found:
        sys.exit("javap not found: put a JDK on PATH or set JAVA_HOME")
    return found


def member(name: str) -> str:
    return f"KEYCODE_{name}" if name[0].isdigit() else name


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    jar = sys.argv[1]
    listing = subprocess.run([javap(), "-constants", "-cp", jar, "android.view.KeyEvent"],
                             check=True, capture_output=True, text=True).stdout
    codes = {m.group(1): int(m.group(2)) for m in re.finditer(r"int KEYCODE_([A-Z0-9_]+) = (\d+);", listing)}
    codes.pop("UNKNOWN", None)
    if len(codes) < 300:
        sys.exit(f"only {len(codes)} key codes found in {jar}: not android.jar?")
    ordered = sorted(codes.items(), key=lambda kv: (kv[1], kv[0]))
    platform = pathlib.Path(jar).parent.name
    PYTHON.write_text("\n".join([
        f'"""Android key codes (``KeyEvent.KEYCODE_*``) for :meth:`Device.press_key`. Generated by',
        f'clients/python/scripts/gen_keys.py from {platform}; do not edit."""',
        "",
        "from __future__ import annotations",
        "",
        "from enum import IntEnum",
        "",
        "",
        "class Key(IntEnum):",
        '    """Every Android key code by its ``KeyEvent`` name without ``KEYCODE_``: ``Key.VOLUME_UP``.',
        "    Names that would start with a digit keep the prefix: ``Key.KEYCODE_0`` is the digit 0.",
        '    A member is an ``int``, so ``press_key`` takes it as it takes any key code."""',
        "",
        *(f"    {member(name)} = {code}" for name, code in ordered),
        "",
    ]))
    KOTLIN.write_text("\n".join([
        f"// Generated by clients/python/scripts/gen_keys.py from {platform}; do not edit.",
        "package io.github.noamcohen48.tap.sdk",
        "",
        "/**",
        " * Every Android key code (`KeyEvent.KEYCODE_*`) for [Device.pressKey], by its name without",
        " * `KEYCODE_`: `Keys.VOLUME_UP`. Names that would start with a digit keep the prefix:",
        " * `Keys.KEYCODE_0` is the digit 0.",
        " */",
        "@Suppress(\"unused\")",
        "object Keys {",
        *(f"    const val {member(name)}: Int = {code}" for name, code in ordered),
        "}",
        "",
    ]))
    print(f"wrote {len(codes)} key codes to {PYTHON} and {KOTLIN}")


if __name__ == "__main__":
    main()
