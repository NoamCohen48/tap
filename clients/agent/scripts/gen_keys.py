"""Generate tap_agent/keycodes.py: every Android KeyEvent KEYCODE_* name and its code.

    python clients/agent/scripts/gen_keys.py ~/Android/Sdk/platforms/android-36/android.jar

Reads the constants with the JDK's javap (on PATH, or JAVA_HOME/bin). Key codes never change
between Android versions; new ones are only added, so the table is regenerated rarely, from the
newest platform. Names become lowercase with dashes (KEYCODE_VOLUME_UP -> volume-up).
"""
from __future__ import annotations

import os
import pathlib
import re
import shutil
import subprocess
import sys

OUT = pathlib.Path(__file__).resolve().parents[1] / "tap_agent" / "keycodes.py"


def javap() -> str:
    home = os.environ.get("JAVA_HOME")
    found = str(pathlib.Path(home) / "bin" / "javap") if home else shutil.which("javap")
    if not found:
        sys.exit("javap not found: put a JDK on PATH or set JAVA_HOME")
    return found


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    jar = sys.argv[1]
    listing = subprocess.run([javap(), "-constants", "-cp", jar, "android.view.KeyEvent"],
                             check=True, capture_output=True, text=True).stdout
    codes = {m.group(1): int(m.group(2)) for m in re.finditer(r"int KEYCODE_([A-Z0-9_]+) = (\d+);", listing)}
    codes.pop("UNKNOWN", None)
    if len(codes) < 300:
        sys.exit(f"only {len(codes)} key codes found in {jar}: not android.jar?")
    platform = pathlib.Path(jar).parent.name
    lines = [
        f'"""Android KeyEvent key codes by name. Generated by clients/agent/scripts/gen_keys.py from',
        f'{platform}; do not edit."""',
        "",
        "CODES: dict[str, int] = {",
        *(f'    "{name.lower().replace("_", "-")}": {code},' for name, code in sorted(codes.items(), key=lambda kv: (kv[1], kv[0]))),
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"wrote {len(codes)} key codes to {OUT}")


if __name__ == "__main__":
    main()
