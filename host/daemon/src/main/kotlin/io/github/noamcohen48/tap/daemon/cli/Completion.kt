package io.github.noamcohen48.tap.daemon.cli

/** Static completion only: completing a word never contacts a daemon or a device. */
internal fun completionScript(shell: String): String {
    val roots = (COMMAND_HELP.keys.map { it.substringBefore(' ') } + "help").distinct()
    val contexts = linkedMapOf("" to (roots + listOf("--state-dir", "--help", "--version")))
    for ((command, spec) in COMMAND_HELP) {
        contexts[command] =
            COMMAND_HELP.keys
                .filter { it.startsWith("$command ") }
                .map { it.removePrefix("$command ").substringBefore(' ') }
                .distinct() +
            spec.options + listOf("--state-dir", "--help", "-h")
    }
    contexts["config"] =
        COMMAND_HELP.keys
            .filter { it.startsWith("config ") }
            .map { it.removePrefix("config ").substringBefore(' ') }
            .distinct() +
        listOf("--state-dir", "--help")
    contexts["completion"] = listOf("bash", "zsh", "fish", "--help")
    contexts["help"] = roots.filterNot { it == "help" }
    val valueOptions = OPTION_HELP.filterValues { it.value != null }.keys.joinToString("|")
    val fileOptions = "--state-dir|--adb|--scrcpy|--scrcpy-server|--driver-apk|--driver-test-apk|--out"
    val d = '$'
    val scan =
        """
        if ((skip)); then skip=0; continue; fi
        case "${d}word" in
          --*=*) continue ;;
          $valueOptions) skip=1; continue ;;
          -*) continue ;;
        esac
        context="$d{context:+${d}context }${d}word"
        """.trimIndent()
    return when (shell) {
        "bash" -> {
            """
            # Generated by tap completion bash. Source this file in bash (3.2+).
            _tap_complete() {
              local cur="$d{COMP_WORDS[COMP_CWORD]}" prev="$d{COMP_WORDS[COMP_CWORD-1]}" context="" word candidate skip=0 i
              COMPREPLY=()
              case "${d}prev" in
                $fileOptions) while IFS= read -r candidate; do COMPREPLY+=("${d}candidate"); done < <(compgen -f -- "${d}cur"); return ;;
                $valueOptions) return ;;
              esac
              for ((i=1; i<COMP_CWORD; i++)); do
                word="$d{COMP_WORDS[i]}"
                $scan
              done
              local choices=""
              case "${d}context" in
            ${contexts.entries.joinToString(
                "\n",
            ) { (context, choices) -> "    '$context') choices='${choices.distinct().joinToString(" ")}' ;;" }}
              esac
              while IFS= read -r candidate; do COMPREPLY+=("${d}candidate"); done < <(compgen -W "${d}choices" -- "${d}cur")
            }
            complete -F _tap_complete tap
            """.trimIndent()
        }

        "zsh" -> {
            """
            #compdef tap
            # Generated by tap completion zsh. Install as _tap on your fpath.
            _tap() {
              local context="" word prev="$d{words[CURRENT-1]}" skip=0 i
              case "${d}prev" in
                $fileOptions) _files; return ;;
                $valueOptions) return ;;
              esac
              for ((i=2; i<CURRENT; i++)); do
                word="$d{words[i]}"
                $scan
              done
              case "${d}context" in
            ${contexts.entries.joinToString(
                "\n",
            ) { (context, choices) -> "    '$context') compadd -- ${choices.distinct().joinToString(" ") { "'$it'" }} ;;" }}
              esac
            }
            _tap "$d@"
            """.trimIndent()
        }

        "fish" -> {
            buildString {
                appendLine("# Generated by tap completion fish. Save in ~/.config/fish/completions/tap.fish")
                appendLine("complete -c tap -f")
                appendLine("complete -c tap -n '__fish_use_subcommand' -a '${roots.joinToString(" ")}'")
                val parents =
                    COMMAND_HELP.keys
                        .flatMap { command ->
                            val words = command.split(' ')
                            (1 until words.size).map { words.take(it).joinToString(" ") }
                        }.distinct()
                for (parent in parents) {
                    val children =
                        COMMAND_HELP.keys
                            .filter {
                                it.startsWith(
                                    "$parent ",
                                )
                            }.map { it.removePrefix("$parent ").substringBefore(' ') }
                            .distinct()
                    val seen = parent.split(' ').joinToString("; and ") { "__fish_seen_subcommand_from $it" }
                    appendLine(
                        "complete -c tap -n '$seen; and not __fish_seen_subcommand_from ${children.joinToString(
                            " ",
                        )}' -a '${children.joinToString(" ")}'",
                    )
                }
                appendLine("complete -c tap -n '__fish_seen_subcommand_from completion' -a 'bash zsh fish'")
                for ((option, spec) in OPTION_HELP) {
                    appendLine(
                        "complete -c tap -l ${option.removePrefix(
                            "--",
                        )}${if (spec.value == null) "" else " -r"}${if (option in
                            fileOptions.split(
                                '|',
                            )
                        ) {
                            " -F"
                        } else {
                            ""
                        }} -d '${spec.description.replace("'", "\\'")}'",
                    )
                }
                appendLine("complete -c tap -s h -l help -d 'Show help'")
                appendLine("complete -c tap -l version -d 'Installed CLI version'")
            }
        }

        else -> {
            error("unsupported shell: $shell")
        }
    }
}
